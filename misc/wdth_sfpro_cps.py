def sfpro_varies(cp):
    if cp is None:
        return False
    for a, b in SFPRO_WDTH_RANGES:
        if a <= cp <= b:
            return True
    return False


# Flattened set for O(1) membership (used in the per-glyph hot loop).
SFPRO_WDTH_CPS = frozenset(
    cp for a, b in SFPRO_WDTH_RANGES for cp in range(a, b + 1)
)
